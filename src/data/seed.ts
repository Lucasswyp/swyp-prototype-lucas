function retentionCurve(base: number): { second: number; percent: number }[] {
  const shape = [100, 92, 84, 71, 63, 58];
  return shape.map((p, i) => ({
    second: i * 2,
    percent: Math.max(20, Math.min(100, p + base)),
  }));
}

